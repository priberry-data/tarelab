// Records the CLI's own welcome screen for the website, so the page replays exactly what a terminal
// prints: the same pixels, colours and words. Run after any change to src/welcome.mjs or the version:
//   node site/build-term.mjs
// Writes site/term-data.js, which site/term.js plays.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { welcome, scene } from "../src/welcome.mjs";

const SITE = path.dirname(fileURLToPath(import.meta.url));
const { version } = JSON.parse(fs.readFileSync(path.join(SITE, "..", "package.json"), "utf8"));
const CONFIG = JSON.parse(fs.readFileSync(path.join(SITE, "term.config.json"), "utf8"));

const screen = welcome({ version, stream: { isTTY: true, columns: 200 }, env: { COLORTERM: "truecolor" } });
if (!screen) throw new Error("welcome() printed nothing");
const ART_W = scene()[0].length;
const hex = (r, g, b) => "#" + [r, g, b].map((v) => Number(v).toString(16).padStart(2, "0")).join("");

// Read the ANSI into cells: each one a character with its colours and weight.
const read = (line) => {
  const cells = [];
  let fg = null, bg = null, bold = false, dim = false, tone = null;
  for (const part of line.split(/(\x1b\[[0-9;]*m)/)) {
    const m = part.match(/^\x1b\[([0-9;]*)m$/);
    if (!m) {
      for (const ch of part) cells.push({ ch, fg, bg, bold, dim, tone });
      continue;
    }
    const p = m[1] === "" ? [0] : m[1].split(";").map(Number);
    for (let i = 0; i < p.length; i++) {
      const n = p[i];
      if (n === 0) (fg = bg = tone = null), (bold = dim = false);
      else if (n === 1) bold = true;
      else if (n === 2) dim = true;
      else if (n === 22) bold = dim = false;
      else if (n === 32) tone = "go";
      else if (n === 33) tone = "amber";
      else if ((n === 38 || n === 48) && p[i + 1] === 2) {
        n === 38 ? (fg = hex(p[i + 2], p[i + 3], p[i + 4])) : (bg = hex(p[i + 2], p[i + 3], p[i + 4]));
        i += 4;
      } else throw new Error(`unknown colour code ${n}`);
    }
  }
  return cells;
};

const palette = [];
const ix = (c) => (c == null ? -1 : palette.includes(c) ? palette.indexOf(c) : palette.push(c) - 1);
const rows = screen.replace(/\n+$/, "").split("\n").slice(1).map((line) => {
  const cells = read(line);
  // The CLI's layout: two spaces, the picture, three spaces, the words.
  const art = cells.slice(2, 2 + ART_W);
  const top = [], bottom = [];
  for (const c of art) {
    if (c.ch === "▀") top.push(c.fg), bottom.push(c.bg);
    else if (c.ch === "▄") top.push(c.bg), bottom.push(c.fg);
    else if (c.ch === " ") top.push(c.bg), bottom.push(c.bg);
    else throw new Error(`unexpected character in the picture: ${c.ch}`);
  }
  const text = [];
  for (const c of cells.slice(2 + ART_W + 3)) {
    const cls = [c.bold && "b", c.dim && "d", c.tone].filter(Boolean).join(" ");
    const last = text[text.length - 1];
    if (last && last[0] === cls) last[1] += c.ch;
    else text.push([cls, c.ch]);
  }
  while (text.length && !text[text.length - 1][1].trim()) text.pop();
  return { p: [...top, ...bottom].map(ix), t: text };
});

const data = { version, command: CONFIG.command, title: CONFIG.title, accent: CONFIG.accent, after: CONFIG.after ?? null, w: ART_W, palette, rows };
fs.writeFileSync(path.join(SITE, "term-data.js"), `// Generated by site/build-term.mjs from src/welcome.mjs. Don't edit by hand.\nwindow.TERM_SCREEN = ${JSON.stringify(data)};\n`);
console.log(`term-data.js: ${rows.length} rows, ${ART_W} pixels wide, ${palette.length} colours, v${version}`);
